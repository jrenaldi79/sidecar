/**
 * Returns an SVG icon string for the given tool name.
 * @param {string} tool - Tool name (case-insensitive).
 * @returns {string} SVG markup string.
 */
function getToolIcon(tool) {
  return TOOL_ICONS[tool.toLowerCase()] || DEFAULT_ICON;
}

